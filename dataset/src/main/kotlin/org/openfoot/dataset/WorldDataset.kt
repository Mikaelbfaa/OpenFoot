package org.openfoot.dataset

import kotlinx.serialization.Serializable
import org.openfoot.model.Country
import org.openfoot.model.Position
import org.openfoot.model.Side
import org.openfoot.model.SpecRef
import org.openfoot.model.Trait

/**
 * Everything world generation needs to build a world, and nothing else.
 *
 * This is our own schema, not a mirror of the original file layout. It carries
 * the fields the simulation actually reads, under names that say what they
 * mean, so a reader does not have to know which single letter held which value.
 * The importer decodes the original files into this; a community dataset or a
 * derivation from public football data fills the same shape.
 *
 * Nothing here performs input or output. These are declarative value types, and
 * reading a file is the job of a module that is allowed to touch a disk.
 *
 * Every type validates its own ranges on construction, which for a serialized
 * type means on decode. A dataset file is untrusted input: it may be
 * hand-edited, generated by a third party tool, or simply stale. Failing loudly
 * at the boundary beats generating a world from a level of 300.
 */
@Serializable
data class WorldDataset(
    val version: Int = CURRENT_VERSION,
    val options: DatasetOptions = DatasetOptions(),
    val countries: List<CountryEntry>,
    val clubs: List<ClubEntry>,
    val leagues: List<LeagueConfigEntry> = emptyList(),
) {
    init {
        require(version == CURRENT_VERSION) {
            "unsupported dataset version $version, this build reads $CURRENT_VERSION"
        }
        require(clubs.isNotEmpty()) { "a dataset with no clubs generates no world" }
        val duplicateClub = clubs.groupingBy { it.ref }.eachCount().entries.firstOrNull { it.value > 1 }
        require(duplicateClub == null) {
            "club ref ${duplicateClub?.key} appears ${duplicateClub?.value} times, and refs seed the generator"
        }
        val duplicateCountry = countries.groupingBy { it.index }.eachCount().entries.firstOrNull { it.value > 1 }
        require(duplicateCountry == null) {
            "country index ${duplicateCountry?.key} appears ${duplicateCountry?.value} times"
        }
    }

    /**
     * The country entry for an index, or null when the dataset omits it.
     * Backed by a map built once, because world generation asks once per
     * player. Lazy and delegated, so nothing here reaches the serialized
     * form of a dataset.
     */
    fun country(index: Int): CountryEntry? = countriesByIndex[index]

    private val countriesByIndex by lazy { countries.associateBy { it.index } }

    companion object {
        /**
         * Bumped whenever a change would make an older file decode into the
         * wrong world rather than fail. Renaming a field or changing the
         * meaning of a value counts; adding an optional field does not.
         *
         * Version 1 is refused rather than read, because division and national
         * team status became world properties assigned at generation time
         * rather than dataset input: a version 1 file's division field would
         * decode successfully and then silently mean nothing.
         */
        const val CURRENT_VERSION = 2
    }
}

/**
 * The options of the original that change what a world is, rather than how it
 * looks.
 *
 * These are read from the installation rather than chosen, because a world built
 * with different options is a different world and a dataset should say which one
 * it describes. Both defaults are what the original ships with.
 */
@Serializable
data class DatasetOptions(
    @property:SpecRef("FORMAT-SPEC, habilidadeIndividual") val individualAbilities: Boolean = false,
    @property:SpecRef("4.8") val monthlyWages: Boolean = true,
)

/**
 * One country, with the strength level that section 4.4 scales players by.
 *
 * The level is the one field here with no source in the original data files.
 * It lives in game code, which the clean room rule puts out of reach, so it is
 * derived instead: the level of the strongest club a country holds. See
 * OPEN-QUESTIONS item 14. That makes it a deliberate divergence, and makes
 * correcting it a data edit rather than a code change.
 *
 * The major league flag marks the five countries section 4.8 pays more in.
 */
@Serializable
data class CountryEntry(
    val index: Int,
    val name: String,
    @property:SpecRef("4.4") val level: Int,
    val continent: Int,
    @property:SpecRef("4.8") val majorLeague: Boolean = false,
) {
    init {
        require(index >= 0) { "country index must not be negative, was $index" }
        require(name.isNotBlank()) { "country $index has a blank name" }
        require(level in LEVEL_RANGE) { "country $index level $level outside $LEVEL_RANGE" }
        require(continent >= 0) { "country $index continent must not be negative, was $continent" }
    }

    companion object {
        /** The same scale club levels use, so the comparison in 4.4 is meaningful. */
        @SpecRef("4.4")
        val LEVEL_RANGE = 1..30
    }
}

/**
 * One club and the squad it fields.
 *
 * The ref is the stable identity, taken from the base name of the original
 * file. The numeric club id of the original is deliberately absent: it is zero
 * for many smaller clubs and not unique across the distributed set, so it
 * cannot key anything. The ref also seeds this club's generator, which is why
 * the dataset rejects duplicates.
 *
 * Division and national team status are absent on purpose. Section 4.4 bands
 * a national team by reputation and everyone else by division, but both are
 * assigned by world generation rather than read from the dataset, so they
 * live on the generated standing rather than here.
 */
@Serializable
data class ClubEntry(
    val ref: String,
    val name: String,
    @property:SpecRef("FORMAT-SPEC, time") val country: Int,
    @property:SpecRef("FORMAT-SPEC, time") val level: Int,
    @property:SpecRef("FORMAT-SPEC, time") val reputation: Int,
    @property:SpecRef("FORMAT-SPEC, estados") val state: Int? = null,
    val stadium: String = "",
    val capacity: Int = 0,
    val coach: String = "",
    val coachCountry: Int = country,
    val squad: List<PlayerEntry> = emptyList(),
) {
    init {
        require(ref.isNotBlank()) { "a club ref must not be blank, it seeds the generator" }
        require(name.isNotBlank()) { "club $ref has a blank name" }
        require(country >= 0) { "club $ref country must not be negative, was $country" }
        require(level in LEVEL_RANGE) { "club $ref level $level outside $LEVEL_RANGE" }
        require(reputation in REPUTATION_RANGE) {
            "club $ref reputation $reputation outside $REPUTATION_RANGE"
        }
        require(state == null || country == Country.BRAZIL) {
            "club $ref carries state $state but country $country, and only Brazil has states"
        }
        require(state == null || state in STATE_RANGE) {
            "club $ref state $state outside $STATE_RANGE"
        }
        require(capacity >= 0) { "club $ref capacity must not be negative, was $capacity" }
    }

    companion object {
        /** Club strength as the original stores it. */
        @SpecRef("FORMAT-SPEC, time")
        val LEVEL_RANGE = 6..20

        /** Reputation, the closest thing the game has to club standing. */
        @SpecRef("5.5")
        val REPUTATION_RANGE = 0..5

        /**
         * The twenty seven Brazilian state championships. Only meaningful when
         * the country is Brazil; elsewhere the original leaves stale bytes in
         * this field, so the importer drops it rather than passing it on.
         */
        @SpecRef("FORMAT-SPEC, estados")
        val STATE_RANGE = 0..26
    }
}

/**
 * One player as the dataset carries him, before world generation runs.
 *
 * Strength and the seven individual abilities are absent on purpose. The
 * original stores no per player strength at all; it is computed from the club
 * and the starter flag when the world is built, so it is an output of
 * generation rather than an input to it. Adding a strength field here would
 * invite a dataset to contradict section 4.4.
 *
 * Talent is carried because the original does store it, but note that every
 * documented effect of it is gated on the player having come through a youth
 * academy. For a player who starts life in a senior squad it currently does
 * nothing. See OPEN-QUESTIONS item 17.
 */
@Serializable
data class PlayerEntry(
    val name: String,
    val age: Int,
    val country: Int,
    val position: Position,
    val side: Side = Side.RIGHT,
    val firstTrait: Trait,
    val secondTrait: Trait,
    @property:SpecRef("FORMAT-SPEC, jogador") val starter: Boolean = false,
    @property:SpecRef("4.10") val star: Boolean = false,
    @property:SpecRef("4.10") val topWorld: Boolean = false,
    @property:SpecRef("4.6") val talent: Int = 0,
) {
    init {
        require(name.isNotBlank()) { "a player of country $country has a blank name" }
        require(age in AGE_RANGE) { "player $name age $age outside $AGE_RANGE" }
        require(country >= 0) { "player $name country must not be negative, was $country" }
        require(talent in TALENT_RANGE) { "player $name talent $talent outside $TALENT_RANGE" }
        require(!topWorld || star) { "player $name is top world without being a star" }
        require(firstTrait.isGoalkeeping == (position == Position.GOALKEEPER)) {
            "player $name plays $position but carries the goalkeeping trait $firstTrait"
        }
        require(secondTrait.isGoalkeeping == (position == Position.GOALKEEPER)) {
            "player $name plays $position but carries the goalkeeping trait $secondTrait"
        }
    }

    companion object {
        /**
         * Wide enough for a youth player and for the oldest the distributed
         * data actually contains, which is fifty six. The retirement table of
         * 4.11 retires everyone past forty eight, so such a player leaves at the
         * first turnover, but he exists on disk and refusing to read him would
         * cost a whole club.
         */
        @SpecRef("4.11")
        val AGE_RANGE = 15..60

        /**
         * Talent runs one to ten, and zero does occur in the distributed files,
         * so zero is accepted rather than treated as corruption.
         */
        @SpecRef("4.6")
        val TALENT_RANGE = 0..10
    }
}

/**
 * One configured tier of a national league.
 *
 * The pyramid generator of section 1.9 consults these before its built in
 * defaults, first match by country and division winning, which is why entry
 * order is preserved and duplicates are legal rather than rejected: a later
 * entry for the same pair is simply never reached, exactly as in the
 * original's concatenated configuration list.
 */
@Serializable
data class LeagueConfigEntry(
    @property:SpecRef("1.9") val country: Int,
    @property:SpecRef("1.9") val division: Int,
    @property:SpecRef("1.9") val teamCount: Int,
    @property:SpecRef("1.9") val relegated: Int,
    @property:SpecRef("1.3") val turns: Int,
    @property:SpecRef("FORMAT-SPEC, desempate") val penaltiesTiebreak: Boolean,
) {
    init {
        require(country >= 0) { "league configuration for negative country $country" }
        require(division in 1..MAX_DIVISION) {
            "league division $division, and section 1.9 builds at most $MAX_DIVISION"
        }
        require(teamCount > 0) { "a league tier of $teamCount teams" }
        require(relegated in 0..teamCount) {
            "$relegated relegated from a tier of $teamCount teams"
        }
        require(turns in 1..MAX_TURNS) { "a league of $turns turns, section 1.3 knows 1 to $MAX_TURNS" }
    }

    companion object {
        @SpecRef("1.9")
        const val MAX_DIVISION = 4

        @SpecRef("1.3")
        const val MAX_TURNS = 4
    }
}
